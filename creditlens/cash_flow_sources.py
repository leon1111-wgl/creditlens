def load_cash_flow_sources(root: Path) -> dict:
    """Read only the pinned server-owned dataset and check the old CFO binding.

    Hashes use canonical JSON, so indentation/line-ending changes are immaterial.
    The raw source PDFs are not required or rehashed by this runtime adapter.
    """
    root = Path(root).resolve()
    path = root / DATASET_PATH
    try:
        _require(path.resolve().is_relative_to(root), "source_path_escape", "Registered source escaped the repository")
        _require(path.stat().st_size <= MAX_BYTES, "source_too_large", "Source dataset exceeds 2 MiB")
        payload = path.read_bytes()
        _require(len(payload) <= MAX_BYTES, "source_too_large", "Source dataset exceeds 2 MiB")
        data = json.loads(payload.decode("utf-8"), object_pairs_hook=_unique_json,
                          parse_constant=lambda value: (_ for _ in ()).throw(ValueError("Non-finite JSON")))
        _require(canonical_sha256(data) == DATASET_SHA256, "source_hash_mismatch", "Registered cash-flow dataset changed")
        validate_source_bundle(data, build_material_bundle(root))
        return data
    except CashFlowSourcesError:
        raise
    except (OSError, UnicodeError, ValueError, TypeError, MaterialsError) as exc:
        raise CashFlowSourcesError("invalid_registered_source", "Cash-flow source or its registered CFO attachment is unavailable") from exc
