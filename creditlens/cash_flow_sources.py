class CashFlowSourcesError(ValueError):
    def __init__(self, code: str, message: str):
        self.code = code
        super().__init__(f"{code}: {message}")


def row_section(spec: dict, role: str) -> tuple[str, str]:
    if role == "reconciliation_adjustments":
        return spec["adjustment_heading"], spec["change_heading"]
    if role == "operating_assets_and_liabilities":
        return spec["change_heading"], spec["end"]
    return spec["start"], spec["end"]


def canonical_sha256(value: object) -> str:
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                     separators=(",", ":"), allow_nan=False).encode("utf-8")).hexdigest()


def _keys(value: object, expected: str, name: str) -> None:
    if type(value) is not dict or set(value) != set(expected.split()):
        raise CashFlowSourcesError("invalid_source_schema", f"Unexpected fields in {name}")


def _require(condition: bool, code: str, message: str) -> None:
    if not condition:
        raise CashFlowSourcesError(code, message)


def _unique_json(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise CashFlowSourcesError("duplicate_json_key", "Duplicate JSON field")
        result[key] = value
    return result


def validate_source_bundle(bundle: dict, materials: dict) -> None:
    """Check the builder output without accepting it as a registered dataset.

    load_cash_flow_sources additionally checks the frozen semantic digest. This
    function is also the offline builder's exact-row and CFO attachment check.
    """
    try:
        _keys(bundle, "schema_version id title material_mode source_versions statements limitations contract", "bundle")
        _require(type(bundle["schema_version"]) is int and bundle["schema_version"] == 1 and
                 bundle["id"] == DATASET_ID and bundle["material_mode"] == "current_verified_materials",
                 "invalid_source_contract", "Wrong dataset version or material mode")
        contract = bundle["contract"]
        _keys(contract, "version formula grouping sign_policy total_excluded_from_components prediction causal_explanation automatic_approval runtime_raw_pdf_rehashed", "contract")
        _require(contract == SOURCE_CONTRACT, "invalid_source_contract", "Source contract changed")
        _require(type(bundle["statements"]) is list and len(bundle["statements"]) == 4 and
                 type(bundle["source_versions"]) is list and len(bundle["source_versions"]) == 2,
                 "incomplete_statements", "Four registered statements and two sources are required")
        source_map = {s["id"]: s for s in materials["source_versions"]}
        cfo_map = {(o["issuer_id"], o["year"]): o for o in materials["observations"] if o["metric"] == "cfo"}
        specs = {s["issuer_id"]: s for s in SOURCE_SPECS}
        seen_sources, seen_statements, seen_facts = set(), set(), set()
        for source in bundle["source_versions"]:
            _keys(source, "id issuer_id source_id title url sha256 published_at retrieved_at filing_metadata_url document_pages cash_flow_page printed_page license server_trusted registered_source_hash_verified raw_pdf_rehashed build_pdf_sha256_verified historical_version_verified", "source")
            registered, spec = source_map[source["id"]], specs[source["issuer_id"]]
            _require(source["id"] not in seen_sources, "duplicate_source", "Repeated source")
            seen_sources.add(source["id"])
            for field in ("id", "issuer_id", "source_id", "title", "url", "sha256", "published_at"):
                _require(source[field] == registered[field], "source_identity_mismatch", "Source differs from registered financial material")
            for key, expected in (("cash_flow_page", spec["page"]), ("printed_page", spec["printed_page"]),
                                  ("document_pages", spec["document_pages"]), ("retrieved_at", spec["retrieved_at"]),
                                  ("filing_metadata_url", spec["filing_metadata_url"]),
                                  ("server_trusted", True), ("registered_source_hash_verified", True),
                                  ("build_pdf_sha256_verified", True), ("raw_pdf_rehashed", False),
                                  ("historical_version_verified", False)):
                _require(type(source[key]) is type(expected) and source[key] == expected,
                         "source_metadata_mismatch", f"Invalid source metadata: {key}")
        for statement in bundle["statements"]:
            _keys(statement, "id issuer_id company year period unit scope basis source_id source_sha256 reported_cfo_observation_id total_fact_id expected_row_keys facts", "statement")
            issuer, year = statement["issuer_id"], statement["year"]
            _require(type(year) is int and (issuer, year) in cfo_map, "unknown_statement", "Unregistered issuer or year")
            cfo, spec = cfo_map[issuer, year], specs[issuer]
            sid = f"{issuer}:cfo-bridge:{year}"
            _require(statement["id"] == sid and sid not in seen_statements, "duplicate_statement", "Invalid or repeated statement identity")
            seen_statements.add(sid)
            _require(statement["company"] == cfo["company"] and statement["source_id"] == cfo["source_version_id"] and
                     statement["source_sha256"] == cfo["source"]["sha256"] and statement["source_id"] in seen_sources,
                     "statement_source_mismatch", "Statement is attached to the wrong source")
            _require(statement["reported_cfo_observation_id"] == cfo["id"], "cfo_attachment_mismatch", "CFO observation identity differs")
            _require(statement["unit"] == cfo["unit"] and statement["scope"] == "reported_consolidated_statement_total" and
                     statement["basis"] == cfo["basis"], "statement_basis_mismatch", "Statement basis or unit differs")
            _keys(statement["period"], "start end days fiscal_calendar kind", "period")
            period = statement["period"]
            _require(period == cfo["period"] and type(period["days"]) is int and
                     period["days"] == (date.fromisoformat(period["end"])-date.fromisoformat(period["start"])).days+1,
                     "statement_period_mismatch", "Statement period differs")
            expected = [r[0] for r in spec["rows"] if r[1] != "cfo_total"]
            _require(statement["expected_row_keys"] == expected and type(statement["facts"]) is list and
                     len(statement["facts"]) == len(spec["rows"]), "incomplete_rows", "Operating section is not complete")
            contribution = Decimal(0)
            for fact, (row_key, role, label_en, label) in zip(statement["facts"], spec["rows"]):
                _keys(fact, "id row_key role label label_en raw_value signed_value source_sha256 page bbox location", "fact")
                fid = f"{statement['source_id']}:cf-bridge-{row_key}-{year}"
                _require(fact["id"] == fid and fid not in seen_facts, "fact_identity_mismatch", "Wrong or repeated global fact identity")
                seen_facts.add(fid)
                _require((fact["row_key"], fact["role"], fact["label_en"], fact["label"]) == (row_key, role, label_en, label),
                         "row_identity_mismatch", "Missing, reordered or relabelled operating row")
                _require(fact["source_sha256"] == statement["source_sha256"] and
                         type(fact["page"]) is int and fact["page"] == spec["page"],
                         "fact_source_mismatch", "Fact refers to the wrong PDF or page")
                _require(type(fact["raw_value"]) is str and type(fact["signed_value"]) is str,
                         "invalid_amount", "Amounts must retain raw and signed decimal strings")
                value = displayed_amount(fact["raw_value"])
                _require(format(value, "f") == fact["signed_value"], "amount_sign_mismatch", "Signed value differs from the displayed amount")
                loc = PdfLocation.model_validate(fact["location"])
                _require(loc.page == spec["page"] and loc.year == year and loc.row_label == label_en and
                         loc.amount_bbox.model_dump(mode="json") == fact["bbox"] and loc.unit_header == "(In millions)",
                         "location_mismatch", "Fact location does not bind its row, amount, period and unit")
                section_start, section_end = row_section(spec, role)
                _require(loc.section is not None and loc.section.start_label == section_start and loc.section.end_label == section_end,
                         "section_mismatch", "Original operating subsection boundaries are required")
                if role == "cfo_total":
                    _require(statement["total_fact_id"] == fid and value == Decimal(cfo["normalized_value"]) and
                             fact["raw_value"] == cfo["raw_value"], "cfo_attachment_mismatch", "CFO amount differs from the existing material")
                    _require(contribution == value, "unreconciled_statement", "Signed operating contributions do not sum to the reported CFO")
                else:
                    contribution += value
        _require(seen_sources == set(source_map) and len(seen_statements) == 4,
                 "incomplete_statements", "Registered sources or statements are missing")
        canonical_sha256(bundle)  # also rejects non-finite coordinate/metadata values
    except CashFlowSourcesError:
        raise
    except (KeyError, TypeError, ValueError, ArithmeticError) as exc:
        raise CashFlowSourcesError("invalid_source_schema", "Malformed cash-flow source data") from exc


