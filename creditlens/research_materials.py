class MaterialsError(ValueError):
    def __init__(self, code: str, message: str):
        self.code = code
        super().__init__(f"{code}: {message}")


def require_material_mode(mode: str) -> None:
    if mode != MATERIAL_MODE:
        raise MaterialsError("historical_version_unverified", "Only current_verified_materials is supported; historical asset availability is not verified")


def _reason(code: str, message: str) -> dict:
    return {"code": code, "message": message}


def _text(value: Decimal) -> str:
    return format(value, "f")


