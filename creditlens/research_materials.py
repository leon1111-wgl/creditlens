def _annual_change(previous: dict, current: dict, adopted: set[str]) -> dict:
    """Pure calculation core. Public entry validates against the trusted bundle."""
    candidates = [previous["id"], current["id"]]
    reasons, warnings = [], []
    row = {
        "issuer_id": current["issuer_id"], "company": current["company"], "metric": current["metric"],
        "from_year": previous["year"], "to_year": current["year"],
        "input_ids": [x for x in candidates if x in adopted], "candidate_observation_ids": candidates,
        "status": "blocked", "reasons": reasons, "warnings": warnings,
        "absolute_change": None, "growth_rate": None, "growth_rate_status": "blocked",
        "formula": {"absolute_change": "current.normalized_value - previous.normalized_value",
                    "growth_rate": "absolute_change / previous.normalized_value"}, "unit": current["unit"],
    }
    if any(x not in adopted for x in candidates):
        reasons.append(_reason("observation_not_adopted", "两期事实必须都明确采用；拒绝或未评估的数据不参与计算。"))
    for field in ("issuer_id", "metric", "unit", "source_version_id", "transformation"):
        if previous[field] != current[field]:
            reasons.append(_reason(f"{field}_mismatch", f"两期的 {field} 不一致。"))
    for field in ("consolidation_scope", "operations_scope", "capex_components", "measurement_basis", "definition"):
        values = [x["basis"].get(field) for x in (previous, current)]
        if any(v in (None, "", "unknown") for v in values):
            reasons.append(_reason("unknown_basis", f"{field} 没有可核验口径。"))
        elif values[0] != values[1]:
            reasons.append(_reason("basis_mismatch", f"两期的 {field} 不一致。"))
    for item in (previous, current):
        for field in ("consolidation_scope", "operations_scope", "capex_components"):
            if not any(e.get("field") == field and e.get("value") == item["basis"].get(field)
                       and e.get("source_sha256") == item["source"]["sha256"] and e.get("page") and e.get("quote")
                       for e in item["basis"].get("scope_evidence", [])):
                reasons.append(_reason("basis_evidence_missing", f"{item['fact_id']} 的 {field} 缺少同来源口径依据。"))
    p, c = previous["period"], current["period"]
    try:
        ps, pe, cs, ce = [date.fromisoformat(x) for x in (p["start"], p["end"], c["start"], c["end"])]
        lengths = [(pe - ps).days + 1, (ce - cs).days + 1]
        if lengths != [p["days"], c["days"]] or min(lengths) <= 0:
            reasons.append(_reason("duration_mismatch", "登记天数与实际日期不一致。"))
        if current["year"] != previous["year"] + 1 or cs != pe + timedelta(days=1) or ce <= pe:
            reasons.append(_reason("annual_order_mismatch", "两期必须为相邻且不重叠的连续年度。"))
        calendar = p["fiscal_calendar"]
        if p["kind"] != "annual" or c["kind"] != "annual" or calendar != c["fiscal_calendar"]:
            reasons.append(_reason("calendar_mismatch", "两期必须使用相同年度日历。"))
        elif calendar == "calendar_year":
            if not (all(n in (365, 366) for n in lengths) and (ps.month, ps.day) == (cs.month, cs.day)
                    and (pe.month, pe.day) == (ce.month, ce.day)):
                reasons.append(_reason("annual_length_mismatch", "日历年度长度或起止边界不一致。"))
            elif lengths[0] != lengths[1]:
                warnings.append(_reason("leap_year_length_difference", "完整日历年度包含闰日差异；按报表原值比较，未日均化或年化。"))
        elif calendar == "week_52_53":
            if lengths[0] not in (364, 371) or lengths[0] != lengths[1]:
                reasons.append(_reason("annual_length_mismatch", "周历年度须同为 52 周或同为 53 周，不自动折算。"))
        else:
            reasons.append(_reason("unknown_calendar", "年度日历未经支持。"))
    except (ValueError, TypeError, KeyError):
        reasons.append(_reason("invalid_period", "年度日期或天数无效。"))
    if reasons:
        return row
    with localcontext() as ctx:
        ctx.prec = 40
        base, value = Decimal(previous["normalized_value"]), Decimal(current["normalized_value"])
        change = value - base
        row.update(status="computed", absolute_change=_text(change))
        if base > 0:
            row.update(growth_rate=_text((change / base).quantize(Decimal("0.000001"), rounding=ROUND_HALF_EVEN)), growth_rate_status="computed")
        else:
            row["growth_rate_status"] = "not_computed_nonpositive_base"
            warnings.append(_reason("nonpositive_base", "基期为零或负值，仅展示绝对变化，不给常规增长率。"))
    return row


def build_comparison(bundle: dict, decisions: list[dict]) -> dict:
    """Use explicit adoption decisions; refuse changed or foreign observations."""
    if type(bundle) is not dict:
        raise MaterialsError("invalid_bundle", "Expected a registered bundle object")
    require_material_mode(bundle.get("material_mode"))
    trusted = build_material_bundle(ROOT, bundle.get("id"))
    try:
        if digest(bundle) != digest(trusted):
            raise MaterialsError("untrusted_bundle", "Bundle contents differ from the server-registered material and contract")
    except (TypeError, ValueError) as exc:
        if isinstance(exc, MaterialsError):
            raise
        raise MaterialsError("invalid_bundle", "Bundle is not JSON-compatible") from exc
    if type(decisions) is not list or len(decisions) > len(bundle["observations"]):
        raise MaterialsError("invalid_decisions", "Decisions must be a bounded list")
    observations = {o["id"]: o for o in bundle["observations"]}
    by_id = {}
    for decision in decisions:
        if type(decision) is not dict or set(decision) != {"observation_id", "decision", "note"}:
            raise MaterialsError("invalid_decision", "Only observation_id, decision and note are accepted")
        oid = decision["observation_id"]
        if type(oid) is not str or oid not in observations:
            raise MaterialsError("unknown_observation", "Observation is not registered in this bundle")
        if oid in by_id:
            raise MaterialsError("duplicate_observation", "An observation may only have one decision")
        if decision["decision"] not in ("adopted", "rejected") or type(decision["note"]) is not str or not decision["note"].strip() or len(decision["note"]) > 2000:
            raise MaterialsError("invalid_decision", "An explicit decision and non-empty bounded note are required")
        by_id[oid] = deepcopy(decision)
    adopted = {oid for oid, d in by_id.items() if d["decision"] == "adopted"}
    rejected = set(by_id) - adopted
    annual, cross = [], []
    for issuer in bundle["issuers"]:
        for metric in _METRICS:
            pair = sorted((o for o in observations.values() if o["issuer_id"] == issuer["id"] and o["metric"] == metric), key=lambda o: o["year"])
            annual.append(_annual_change(pair[0], pair[1], adopted))
    for metric in _METRICS:
        for year in _YEARS:
            items = [o for o in observations.values() if o["metric"] == metric and o["year"] == year]
            reasons = [_reason("not_strict_peer_benchmark", "微软/苹果为跨公司流程样例，未建立严格同行比较契约。")]
            if len({(o["period"]["start"], o["period"]["end"]) for o in items}) != 1:
                reasons.append(_reason("actual_period_mismatch", "相同 FY 标签不代表相同实际期间；本组开始日与结束日不同。"))
            if len({(o["period"]["fiscal_calendar"], o["period"]["days"]) for o in items}) != 1:
                reasons.append(_reason("annual_calendar_mismatch", "日历年度与周历年度长度不同，不自动年化。"))
            if any(o["id"] not in adopted for o in items):
                reasons.append(_reason("observation_not_adopted", "未采用的观察值不参与比较。"))
            cross.append({"metric": metric, "year": year, "observation_ids": [o["id"] for o in items if o["id"] in adopted],
                          "candidate_observation_ids": [o["id"] for o in items], "status": "side_by_side_only", "reasons": reasons, "ranking": None})
    return {
        "rule_version": MATERIAL_RULE_VERSION, "bundle_id": bundle["id"], "material_mode": MATERIAL_MODE,
        "decisions": [by_id[oid] for oid in sorted(by_id)], "adopted_observation_ids": sorted(adopted),
        "rejected_observation_ids": sorted(rejected), "unassessed_observation_ids": sorted(set(observations) - set(by_id)),
        "annual_changes": annual, "cross_company": cross, "limitations": deepcopy(bundle["limitations"]),
        "prediction": False, "automatic_approval": False,
    }
