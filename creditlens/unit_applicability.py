class UnitApplicabilityError(ValueError):
    def __init__(self, code, path, message="单位核对输入不符合固定契约。"):
        self.code, self.path, self.message = code, path, message
        super().__init__(message)


def _require(ok, path):
    if not ok:
        raise UnitApplicabilityError("invalid_extraction", path)


def _finite_json(value, depth=0, count=None):
    count = [0] if count is None else count
    count[0] += 1
    _require(depth <= 24 and count[0] <= 20000, "extraction")
    if type(value) is dict:
        _require(all(type(k) is str for k in value), "extraction")
        for item in value.values(): _finite_json(item, depth + 1, count)
    elif type(value) is list:
        for item in value: _finite_json(item, depth + 1, count)
    else:
        _require(type(value) in (str, bool, int, float, type(None)), "extraction")
        if type(value) is float: _require(math.isfinite(value), "extraction")


def _span(item, path):
    _require(type(item) is dict and set(item) == {"span_index", "span"}, path)
    _require(type(item["span_index"]) is int and item["span_index"] >= 0, path)
    span = item["span"]
    _require(type(span) is dict and set(span) == {"text", "confidence", "bbox"}, path)
    _require(type(span["text"]) is str and 0 < len(span["text"]) <= 20000, path)
    _require(type(span["confidence"]) in (int, float) and 0 <= span["confidence"] <= 1, path)
    box = span["bbox"]
    _require(type(box) is dict and set(box) == {"x0", "top", "x1", "bottom"}, path)
    _require(all(type(v) in (int, float) and abs(v) <= 1e9 and (type(v) is int or math.isfinite(v)) for v in box.values()), path)
    _require(0 <= box["x0"] < box["x1"] and 0 <= box["top"] < box["bottom"], path)


def _validate(row_label, extraction):
    _require(type(row_label) is str and 0 < len(row_label) <= 500 and bool(normalize_row_label(row_label)), "row_label")
    _require(type(extraction) is dict and _BASE <= set(extraction) <= _BASE | _EXTRA, "extraction")
    _finite_json(extraction)
    _require(type(extraction["method"]) is str and extraction["method"] in _METHODS
             and type(extraction["status"]) is str and extraction["status"] in ("selected", "insufficient"), "extraction")
    _require(extraction["automatic_approval"] is False, "extraction.automatic_approval")
    for field in ("reason", "message"):
        _require(type(extraction[field]) is str, "extraction")
    unit = extraction["unit"]
    _require(type(unit) is dict and set(unit) == {"raw_text", "scale", "currency", "qualifier_present"}, "extraction.unit")
    _require(type(unit["qualifier_present"]) is bool and all(unit[k] is None or type(unit[k]) is str for k in ("raw_text", "scale", "currency")), "extraction.unit")
    evidence = extraction["evidence"]
    _require(type(evidence) is dict and set(evidence) == {"row_label", "unit", "amounts", "year_headers", "guards"}, "extraction.evidence")
    for role, items in evidence.items():
        _require(type(items) is list and len(items) <= 2000, "extraction.evidence")
        for item in items: _span(item, "extraction.evidence." + role)
    for field in ("raw_value", "normalized_value"):
        _require(extraction[field] is None or type(extraction[field]) is str, "extraction." + field)
    _require(extraction["selected_span_index"] is None or (type(extraction["selected_span_index"]) is int and extraction["selected_span_index"] >= 0), "extraction.selected_span_index")


def _statement(raw):
    value = " ".join(unicodedata.normalize("NFKC", raw).casefold().split())
    if value.startswith("(") and value.endswith(")"):
        inner = value[1:-1]
    else:
        inner = value
    scale = r"(millions|thousands|billions)"
    patterns = [
        ("plain_scale", rf"in {scale}"),
        ("per_share_exception", rf"in {scale}, except per[ -]share amounts"),
        ("share_count_and_per_share_exceptions", rf"in {scale}, except number of shares, which are reflected in {scale}, and per[ -]share amounts"),
        ("share_count_and_par_value_exceptions", rf"in {scale}, except number of shares, which are reflected in {scale}, and par value"),
    ]
    for grammar, pattern in patterns:
        match = re.fullmatch(pattern, inner)
        if match:
            exceptions = []
            if grammar.startswith("share_count"):
                exceptions.append({"category": "share_count", "scale": match.group(2)[:-1], "applicability": "excluded_from_base_scale"})
            if grammar != "plain_scale":
                exceptions.append({"category": "par_value" if "par_value" in grammar else "per_share_amount", "scale": None, "applicability": "excluded_from_base_scale"})
            return {"raw_text": raw, "normalized_text": value, "grammar_id": grammar, "base_scale": match.group(1)[:-1], "exceptions": exceptions}
    return None


def _row_category(row_label):
    label = normalize_row_label(row_label)
    if (label in {"basic", "diluted", "basic and diluted", "basic / diluted", "eps"}
            or re.search(r"^(?:basic|diluted)(?:\s|$)|^shares?$|\b(?:per(?:[ -]common)?[ -]share|par value|number of shares|share count|shares? outstanding|weighted[ -]average|ratio|percentage|percent)\b|%", label)
            or label.endswith("margin") or label.endswith("margin rate")):
        return "ambiguous_or_nonmonetary"
    if label in _MONETARY_LABELS:
        return "supported_monetary_label"
    return "unknown"


def inspect_unit_applicability(*, row_label: str, extraction: dict) -> dict:
    _validate(row_label, extraction)
    try:
        encoded = json.dumps({"row_label": row_label, "extraction": extraction}, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False).encode("utf8")
        _require(len(encoded) <= 256 * 1024, "extraction")
    except (ValueError, UnicodeError, OverflowError) as exc:
        if isinstance(exc, UnitApplicabilityError): raise
        raise UnitApplicabilityError("invalid_extraction", "extraction") from exc
    result = {"schema_version": 1, "rule_version": UNIT_APPLICABILITY_VERSION, "status": "blocked", "unit_ready": False,
              "scale": None, "scale_factor": None, "scaled_value": None,
              "original_candidate": {k: deepcopy(extraction[k]) for k in ("method", "status", "reason", "raw_value", "normalized_value", "selected_span_index", "unit")},
              "unit_statement": None, "row_category": _row_category(row_label),
              "evidence": {"row_label": deepcopy(extraction["evidence"]["row_label"]), "unit": deepcopy(extraction["evidence"]["unit"]), "amount": []},
              "reasons": [], "input_sha256": hashlib.sha256(encoded).hexdigest(),
              "scope": {"evidence_basis": "saved_extraction_fragments", "full_page_replayed": False, "upstream_selection_reexecuted": False, "unit_applicability_only": True, "currency": "unknown", "financial_period": "unknown", "financial_scope": "unknown", "independent_human_gold": False, "source_authenticity_verified": False},
              "automatic_approval": False}
    def issue(code):
        if code not in {r["code"] for r in result["reasons"]}:
            result["reasons"].append({"code": code, "message": _MESSAGES[code]})
    if extraction["status"] != "selected":
        result["status"] = "not_selected"; issue("candidate_not_selected"); return result
    if extraction.get("guard_issues"):
        issue("candidate_guard_unresolved")
    units, rows = extraction["evidence"]["unit"], extraction["evidence"]["row_label"]
    amounts = [a for a in extraction["evidence"]["amounts"] if a["span_index"] == extraction["selected_span_index"]]
    result["evidence"]["amount"] = deepcopy(amounts)
    if len(units) != 1 or units[0]["span"]["text"] != extraction["unit"]["raw_text"]:
        issue("unit_evidence_mismatch")
    else:
        result["unit_statement"] = _statement(units[0]["span"]["text"])
        if result["unit_statement"] is None:
            issue("unsupported_unit_statement")
        elif (extraction["unit"]["scale"] != result["unit_statement"]["base_scale"]
              or extraction["unit"]["qualifier_present"] != bool(result["unit_statement"]["exceptions"])
              or extraction["unit"]["currency"] is not None):
            issue("unit_declaration_mismatch")
    if len(rows) != 1 or normalize_row_label(rows[0]["span"]["text"]) != normalize_row_label(row_label):
        issue("row_evidence_mismatch")
    numeric = None
    if len(amounts) != 1 or amounts[0]["span"]["text"] != extraction["raw_value"]:
        issue("amount_evidence_mismatch")
    else:
        try:
            with localcontext(Context(prec=128)):
                numeric = parse_lookup_amount(extraction["raw_value"])
            if numeric != extraction["normalized_value"]: issue("amount_evidence_mismatch")
        except (TableLookupError, ValueError): issue("amount_evidence_mismatch")
    refs = [*units, *rows, *amounts]
    if len({r["span_index"] for r in refs}) != len(refs): issue("evidence_index_conflict")
    if any(r["span"]["confidence"] < MIN_CONFIDENCE for r in refs): issue("low_confidence")
    if result["row_category"] == "ambiguous_or_nonmonetary": issue("ambiguous_unit_category")
    if result["unit_statement"] and result["unit_statement"]["exceptions"] and result["row_category"] == "unknown":
        issue("unknown_exception_row_category")
    if not result["reasons"]:
        scale = result["unit_statement"]["base_scale"]
        with localcontext(Context(prec=128)):
            scaled = format(Decimal(numeric) * Decimal(_SCALES[scale]), "f")
        result.update(status="unit_ready", unit_ready=True, scale=scale, scale_factor=_SCALES[scale], scaled_value=scaled)
    return result
