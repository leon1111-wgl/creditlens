"""Reproduce Apple's pinned FY2025 PDF adapter and report its development checks.

No generic layout claim, OCR, model inference or paid API. Reference values are
loaded only after extraction; full documents and rendered pages stay local.
"""
from datetime import datetime, timezone
from pathlib import Path
import argparse
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from creditlens.diligence import CasePack, digest, displayed_amount
from creditlens.document import EvidenceError, STACKED_PARSER_VERSION, extract_stacked_table, extract_table, pdfium_tokens
from scripts.build_pdf_pack import verified_pdf, write_json, LABELS

URL = "https://s2.q4cdn.com/470004039/files/doc_financials/2025/ar/_10-K-2025-As-Filed.pdf"
SHA256 = "3eb270b22acb7d8d8e9c32a43dc221dec3345f8e4bca02755fdbc1ee16c823de"
FILING = "https://www.sec.gov/Archives/edgar/data/320193/000032019325000079/0000320193-25-000079-index.htm"
PERIODS = {2025: ("2024-09-29", "2025-09-27"), 2024: ("2023-10-01", "2024-09-28")}
TABLES = [
    {"page": 32, "title": "CONSOLIDATED STATEMENTS OF OPERATIONS",
     "unit_header": "(In millions, except number of shares, which are reflected in thousands, and per-share amounts)",
     "years": [2025, 2024, 2023], "date_headers": ["September 27,", "September 28,", "September 30,"],
     "duration_header": "Years ended", "metrics": {"revenue": "Total net sales"}},
    {"page": 34, "title": "CONSOLIDATED BALANCE SHEETS",
     "unit_header": "(In millions, except number of shares, which are reflected in thousands, and par value)",
     "years": [2025, 2024], "date_headers": ["September 27,", "September 28,"],
     "metrics": {
         "cash_equivalents": {"label": "Cash and cash equivalents", "section": ["Current assets:", "Total current assets"]},
         "short_investments": {"label": "Marketable securities", "section": ["Current assets:", "Total current assets"]},
         "short_debt": {"label": "Commercial paper", "section": ["Current liabilities:", "Total current liabilities"]},
         "current_debt": {"label": "Term debt", "section": ["Current liabilities:", "Total current liabilities"]},
         "long_debt": {"label": "Term debt", "section": ["Non-current liabilities:", "Total non-current liabilities"]},
         "current_assets": "Total current assets", "current_liabilities": "Total current liabilities"}},
    {"page": 36, "title": "CONSOLIDATED STATEMENTS OF CASH FLOWS", "unit_header": "(In millions)",
     "years": [2025, 2024, 2023], "date_headers": ["September 27,", "September 28,", "September 30,"],
     "duration_header": "Years ended", "metrics": {"cfo": "Cash generated by operating activities",
       "capex": "Payments for acquisition of property, plant and equipment", "net_income": "Net income"}},
]
APPLE_LABELS = {**LABELS, "cash_equivalents": "现金及现金等价物", "short_investments": "流动有价证券"}


def build(path, render_dir=None):
    import pypdfium2 as pdfium
    records, baseline = [], []
    with pdfium.PdfDocument(path) as pdf:
        if len(pdf) != 80:
            raise EvidenceError("Unexpected Apple document page count")
        for spec in TABLES:
            page = pdf[spec["page"]-1]
            try:
                if page.get_rotation() != 0:
                    raise EvidenceError("Rotated page requires another adapter")
                tokens = pdfium_tokens(page)
                # Capture the old header assumption's refusal, not a misleading accuracy score.
                old = {k: spec[k] for k in ("page", "title", "unit_header", "years")}
                old["period_header"] = spec.get("duration_header", spec["date_headers"][0])
                old["metrics"] = {m: s if isinstance(s, str) else s["label"] for m, s in spec["metrics"].items()}
                try:
                    extract_table(tokens, width=page.get_width(), height=page.get_height(), **old)
                    baseline.append({"page": spec["page"], "status": "accepted"})
                except EvidenceError as exc:
                    baseline.append({"page": spec["page"], "status": "refused", "reason": str(exc)})
                items = extract_stacked_table(tokens, width=page.get_width(), height=page.get_height(), **spec)
                selected = [r for r in items if r["year"] in PERIODS]
                records.extend(selected)
                if render_dir:
                    from PIL import ImageDraw
                    render_dir.mkdir(parents=True, exist_ok=True)
                    bitmap = page.render(scale=1.8)
                    try:
                        preview = bitmap.to_pil().copy()
                    finally:
                        bitmap.close()
                    draw = ImageDraw.Draw(preview)
                    for item in selected:
                        loc = item["pdf_location"]
                        regions = [(loc[k], c) for k, c in [("amount_bbox", "#167c52"), ("row_label_bbox", "#275eb4"),
                                   ("period_bbox", "#b45b00"), ("unit_bbox", "#884ba0")]]
                        if loc.get("section"):
                            regions += [(loc["section"][k], "#aa3344") for k in ("start_bbox", "end_bbox")]
                        for b, color in regions:
                            draw.rectangle(tuple(b[k]*1.8 for k in ("x0", "top", "x1", "bottom")), outline=color, width=2)
                    preview.save(render_dir/f"aapl-page-{spec['page']}-evidence.png")
            finally:
                page.close()
    facts = []
    for r in records:
        metric, year, loc = r["metric"], r["year"], r["pdf_location"]
        section = " / " + loc["section"]["start_label"] if loc.get("section") else ""
        facts.append({"id": f"{metric}-{year}", "metric": metric, "label": APPLE_LABELS[metric],
            "value": r["value"], "raw_value": r["raw_value"], "unit": "USD_million",
            "period_start": PERIODS[year][0] if metric in {"cfo", "capex", "net_income", "revenue"} else None,
            "period_end": PERIODS[year][1], "source_id": "aapl-fy25-10k-pdf",
            "locator": f"PDF p.{loc['page']} (printed {loc['page']-3}) / {loc['row_label']}{section} / FY{year}",
            "transformation": "absolute_cash_outflow" if metric == "capex" else "displayed_magnitude", "pdf_location": loc})
    pack = CasePack.model_validate({"entity_id": "AAPL", "company": "Apple Inc.", "title": "FY2025 苹果现金流与债务复核",
        "fiscal_calendar": "week_52_53", "sources": [{"id": "aapl-fy25-10k-pdf", "title": "Apple FY2025 Form 10-K / official PDF",
        "url": URL, "published_at": "2025-10-31", "sha256": SHA256}], "facts": facts})
    return pack, baseline, str(pdfium.PYPDFIUM_INFO), str(pdfium.PDFIUM_INFO)


def compare_reference(pack, reference):
    expected = {}
    for row in reference["rows"]:
        for year, raw in zip(reference["years"], row["raw_values"]):
            start, end = reference["periods"][str(year)]
            amount = displayed_amount(raw)
            expected[f"{row['metric']}-{year}"] = {
                "value": str(abs(amount) if row["metric"] == "capex" else amount), "metric": row["metric"],
                "unit": reference["unit"], "period_start": start if row["flow"] else None, "period_end": end,
                "raw_value": raw, "transformation": "absolute_cash_outflow" if row["metric"] == "capex" else "displayed_magnitude"}
    checks = []
    for fact in pack.facts:
        payload, ref = fact.model_dump(mode="json"), expected.get(fact.id)
        differences = [k for k in ref if payload[k] != ref[k]] if ref else ["unexpected_fact"]
        checks.append({"fact_id": fact.id, "pdf_value": str(fact.value), "reference_value": ref["value"] if ref else None,
                       "physical_page": fact.pdf_location.page, "matched": not differences, "different_fields": differences})
    return {"compared": len(checks), "matched": sum(c["matched"] for c in checks),
            "missing_pdf_fact_ids": sorted(set(expected)-{f.id for f in pack.facts}), "checks": checks}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pdf", type=Path, default=ROOT/"data/raw/aapl-fy2025-10k.pdf")
    parser.add_argument("--download", action="store_true")
    parser.add_argument("--render-dir", type=Path)
    args = parser.parse_args()
    retrieved = verified_pdf(args.pdf, args.download, url=URL, sha256=SHA256)
    pack, baseline, wrapper, engine = build(args.pdf, args.render_dir)
    reference = json.loads((ROOT/"data/reference/aapl-fy2025-reference.json").read_text(encoding="utf-8"))
    report = compare_reference(pack, reference)
    report.update({"generated_at": datetime.now(timezone.utc).isoformat(), "parser_version": STACKED_PARSER_VERSION,
                   "source_sha256": SHA256, "reference_sha256": digest(reference), "old_header_adapter": baseline,
                   "scope": "Development checks against a developer-transcribed filing reference; not held-out accuracy or authenticity."})
    write_json(ROOT/"artifacts/aapl-pdf-crosscheck.json", report)
    if report["compared"] != 22 or report["matched"] != 22 or report["missing_pdf_fact_ids"]:
        raise EvidenceError("Apple reference mismatch; example pack was not replaced")
    write_json(ROOT/"data/examples/aapl-fy2025-pdf.json", pack.model_dump(mode="json"))
    write_json(ROOT/"data/examples/aapl-pdf-provenance.json", {
        "source_url": URL, "source_sha256": SHA256, "filing_metadata_url": FILING,
        "accession": "0000320193-25-000079", "filed_at": "2025-10-31", "retrieved_at": retrieved["retrieved_at"],
        "document_pages": 80, "selected_physical_pages": [32, 34, 36], "selected_printed_pages": [29, 31, 33],
        "facts": 22, "pack_sha256": digest(pack.model_dump(mode="json")), "profile_sha256": digest(TABLES), "profile": TABLES,
        "parser_version": STACKED_PARSER_VERSION, "pypdfium2_version": wrapper, "pdfium_version": engine,
        "fiscal_calendar": "52/53-week year ending on the last Saturday of September; both selected flow years are 52 weeks.",
        "currency_basis": "USD per issuer financial reporting convention; the page unit header supplies millions.",
        "reference": reference,
        "license": "Issuer filing, public access without a general redistribution grant. Full PDF, HTML and page renders excluded.",
        "limitations": ["Two pinned issuer layouts, not unseen-company evaluation, generic parsing, OCR or VLM.",
                        "Current PDF byte version is not proven to have existed on the filing date.",
                        "FY2024 comparison is known from FY2025 disclosure, not a historical FY2024 snapshot.",
                        "Liquidity adds cash and current marketable securities; long-term securities, restrictions, leases and guarantees require review."]})
    print(json.dumps({k: report[k] for k in ("compared", "matched", "missing_pdf_fact_ids", "old_header_adapter")}))


if __name__ == "__main__":
    main()
